import { AccountId } from '../../../../src/domain/account/value-objects/account-id-value-object';
import { Currency } from '../../../../src/domain/shared/value-objects/currency-value-object';
import { Money } from '../../../../src/domain/shared/value-objects/money-value-object';
import { Wallet } from '../../../../src/domain/wallet/entities/wallet';
import { WalletId } from '../../../../src/domain/wallet/value-objects/wallet-id-value-object';
import { WalletStatus } from '../../../../src/domain/wallet/value-objects/wallet-status-value-object';
import { pool } from '../../../../src/infra/config/database/postgresql/pg';
import { PostgresWalletRepository } from '../../../../src/infra/persistence/postgresql/postgres-wallet-repository';
import { closeLabPool, createLabAccount, deleteLabAccount } from '../../../concurrency/support/db';

function fields(wallet: Wallet | null) {
  if (!wallet) return null;
  return {
    id: wallet.getId().getValue(),
    accountId: wallet.getAccountId().getValue(),
    currency: wallet.getCurrency().getCode(),
    balance: wallet.getBalance().getAmountMinorUnits(),
    status: wallet.getStatus().getId(),
    createdAt: wallet.getCreatedAt(),
  };
}

describe('PostgresWalletRepository (real Postgres)', () => {
  const repository = new PostgresWalletRepository();
  let accounts: string[];
  let accountId: AccountId;

  async function ownAccount(): Promise<AccountId> {
    const id = await createLabAccount();
    accounts.push(id);
    return AccountId.from(id);
  }

  function wallet(): Wallet {
    const currency = Currency.from('USD');
    return new Wallet(
      WalletId.generate(),
      accountId,
      currency,
      Money.fromMinorUnits(123456789, currency),
      WalletStatus.active(),
      new Date('2026-10-15T12:34:56.789Z')
    );
  }

  beforeEach(async () => {
    accounts = [];
    accountId = await ownAccount();
  });

  afterEach(async () => {
    // Every deletion is restricted to accounts generated by this test.
    // allSettled ensures one cleanup failure does not strand other fixtures.
    const results = await Promise.allSettled(accounts.map(deleteLabAccount));
    for (const result of results) {
      if (result.status === 'rejected') throw result.reason;
    }
    const remaining = await pool.query(
      `SELECT id FROM wallets WHERE account_id = ANY($1::uuid[])
       UNION ALL SELECT id FROM accounts WHERE id = ANY($1::uuid[])`,
      [accounts]
    );
    expect(remaining.rows).toEqual([]);
  });

  afterAll(closeLabPool);

  it('save then findById round-trips every mapped column', async () => {
    const original = wallet();
    await repository.save(original);
    expect(fields(await repository.findById(original.getId()))).toEqual(fields(original));
  });

  it('findByAccountIdAndCurrency returns the saved wallet', async () => {
    const original = wallet();
    await repository.save(original);
    expect(
      fields(await repository.findByAccountIdAndCurrency(accountId, original.getCurrency()))
    ).toEqual(fields(original));
  });

  it('findByAccountIdAndCurrency returns null for another currency', async () => {
    await repository.save(wallet());
    expect(await repository.findByAccountIdAndCurrency(accountId, Currency.from('EUR'))).toBeNull();
  });

  it('findByAccountIdAndCurrency returns null for another account', async () => {
    await repository.save(wallet());
    const otherAccount = await ownAccount();
    expect(
      await repository.findByAccountIdAndCurrency(otherAccount, Currency.from('USD'))
    ).toBeNull();
  });

  it('upsert updates balance and status while preserving identity and creation columns', async () => {
    const original = wallet();
    await repository.save(original);
    const otherAccount = await ownAccount();
    const currency = Currency.from('EUR');
    // Deliberately offer different immutable columns: the conflict path must
    // preserve the persisted values, rather than merely receiving equal ones.
    const update = new Wallet(
      original.getId(),
      otherAccount,
      currency,
      Money.fromMinorUnits(987654321, currency),
      WalletStatus.closed(),
      new Date('2026-10-16T00:00:00.000Z')
    );
    await repository.save(update);
    expect(fields(await repository.findById(original.getId()))).toEqual({
      ...fields(original),
      balance: 987654321,
      status: 2,
    });
    expect(await repository.findByAccountIdAndCurrency(otherAccount, currency)).toBeNull();
  });

  it('rejects another id for the same account and currency with Postgres code 23505', async () => {
    const original = wallet();
    const duplicate = wallet();
    expect(duplicate.getId().getValue()).not.toBe(original.getId().getValue());
    await repository.save(original);
    await expect(repository.save(duplicate)).rejects.toMatchObject({ code: '23505' });
    expect(fields(await repository.findById(original.getId()))).toEqual(fields(original));
    expect(await repository.findById(duplicate.getId())).toBeNull();
  });
});
